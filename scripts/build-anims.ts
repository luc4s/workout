// Builds public/anims/<exerciseId>.glb from the pose specs in src/anim3d/exercises.
// Usage: npx vite-node scripts/build-anims.ts
import { mkdirSync, writeFileSync } from 'node:fs';
import { GLTFExporter } from 'three/examples/jsm/exporters/GLTFExporter.js';
import { buildExercise } from '../src/anim3d/build';
import { ANIM_SPECS } from '../src/anim3d/exercises';

// GLTFExporter reads its output through FileReader, which Node lacks.
class NodeFileReader {
  result: ArrayBuffer | string | null = null;
  onloadend: (() => void) | null = null;
  readAsArrayBuffer(blob: Blob) {
    blob.arrayBuffer().then((buf) => {
      this.result = buf;
      this.onloadend?.();
    });
  }
  readAsDataURL(blob: Blob) {
    blob.arrayBuffer().then((buf) => {
      this.result = `data:${blob.type || 'application/octet-stream'};base64,${Buffer.from(buf).toString('base64')}`;
      this.onloadend?.();
    });
  }
}
(globalThis as unknown as { FileReader: unknown }).FileReader ??= NodeFileReader;

const out = new URL('../public/anims/', import.meta.url);
mkdirSync(out, { recursive: true });
const exporter = new GLTFExporter();
let total = 0;
for (const spec of Object.values(ANIM_SPECS)) {
  const { scene, clips } = buildExercise(spec);
  const glb = (await exporter.parseAsync(scene, { binary: true, animations: clips })) as ArrayBuffer;
  writeFileSync(new URL(`${spec.id}.glb`, out), Buffer.from(glb));
  total += glb.byteLength;
  console.log(`${spec.id}.glb  ${(glb.byteLength / 1024).toFixed(0)} KB  clips: ${clips.map((c) => c.name).join(', ')}`);
}
console.log(`total ${(total / 1024).toFixed(0)} KB`);

// Human-readable list of what each animation is based on (committed, so it can be reviewed).
const md = [
  '# Animation references',
  '',
  'Generated by `npm run anims` from `src/anim3d/exercises/*.ts` — edit the specs, not this file.',
  'Start / end photos come from [free-exercise-db](https://github.com/yuhonas/free-exercise-db) (public domain, Unlicense);',
  'segment lengths from D. A. Winter, *Biomechanics and Motor Control of Human Movement*.',
  '',
  ...Object.values(ANIM_SPECS).flatMap((spec) => [
    `## ${spec.id}`,
    '',
    ...spec.references.map((r) => `- [${r.title}](${r.url}) — ${r.note}`),
    ...(spec.faults.length ? [`- Mistake demos: ${spec.faults.map((f) => f.title).join('; ')}`] : []),
    '',
  ]),
].join('\n');
writeFileSync(new URL('../src/anim3d/REFERENCES.md', import.meta.url), md);
